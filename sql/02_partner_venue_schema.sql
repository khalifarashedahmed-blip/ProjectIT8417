-- Schema 2: partner_venue  (legacy partner system, deliberately different from citywide_events)
-- Differences: text/identity keys instead of SERIAL, full_name instead of first/last,
-- no ticket_type table (seat_class is free text), and purchase copies show_name + seat_price.

CREATE SCHEMA IF NOT EXISTS partner_venue;
SET search_path TO partner_venue;

CREATE TABLE venue (
    venue_code      VARCHAR(10)  PRIMARY KEY,               -- e.g. 'V01'
    venue_name      VARCHAR(80)  NOT NULL,
    city            VARCHAR(50)  NOT NULL,
    seating_capacity INT,
    manager_contact VARCHAR(80),                            -- not needed downstream (dropped in ETL)
    parking_notes   TEXT                                    -- not needed downstream (dropped in ETL)
);

CREATE TABLE guest (
    guest_no      INT GENERATED BY DEFAULT AS IDENTITY (START WITH 5001) PRIMARY KEY,
    full_name     VARCHAR(100) NOT NULL,                    -- one field, unlike first_name/last_name
    email         VARCHAR(120),                             -- no UNIQUE, mixed case allowed
    mobile        VARCHAR(20),                              -- not needed downstream (dropped in ETL)
    loyalty_tier  VARCHAR(10),                              -- Bronze/Silver/Gold; not in citywide_events
    referral_code VARCHAR(20)                               -- not needed downstream (dropped in ETL)
);

CREATE TABLE show (
    show_code      VARCHAR(12)  PRIMARY KEY,                -- e.g. 'PV-001'
    show_title     VARCHAR(120) NOT NULL,
    genre          VARCHAR(40),                             -- = category in citywide_events
    blurb          TEXT,                                    -- = description in citywide_events
    venue_code     VARCHAR(10)  NOT NULL REFERENCES venue(venue_code),
    show_datetime  TIMESTAMP    NOT NULL,                   -- timestamp, not a plain date
    promoter_notes TEXT,                                    -- not needed downstream (dropped in ETL)
    banner_image   VARCHAR(255)                             -- not needed downstream (dropped in ETL)
);

CREATE TABLE purchase (
    purchase_no     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guest_no        INT          NOT NULL REFERENCES guest(guest_no),
    show_code       VARCHAR(12)  NOT NULL REFERENCES show(show_code),
    show_name       VARCHAR(120),                           -- denormalised copy of show.show_title
    seat_class      VARCHAR(30),                            -- free text: 'VIP', 'vip', 'General Admission'...
    seat_price      NUMERIC(8,2),                           -- denormalised: price copied at time of sale
    qty             INT          NOT NULL CHECK (qty > 0),
    purchased_on    TIMESTAMP    NOT NULL DEFAULT NOW(),
    comp_code       VARCHAR(20),                            -- not needed downstream (dropped in ETL)
    till_receipt_no VARCHAR(30)                             -- not needed downstream (dropped in ETL)
);
